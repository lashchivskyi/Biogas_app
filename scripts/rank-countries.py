def score(v):
    keys = list(W)
    return sum(W[k][0] * v[i] for i, k in enumerate(keys)) / 5 * 100

def main():
    rows = []
    for name, v in C.items():
        *s, tags, note = v
        rows.append({"country": name, "score": round(score(s), 1), "criteria": dict(zip(W, s)), "evidence": tags, "note": note})
    rows.sort(key=lambda r: -r["score"])
    Path("docs/data").mkdir(parents=True, exist_ok=True)
    Path("docs/data/country-ranking.json").write_text(json.dumps({"weights": {k: w[0] for k, w in W.items()}, "rows": rows}, ensure_ascii=False, indent=1), encoding="utf-8")
    for i, r in enumerate(rows, 1):
        print(f"{i:2d}. {r['country']:16s} {r['score']:5.1f}  [{r['evidence']}]")

if __name__ == "__main__":
    main()
